"""Силуэты объектов для раскладки: каждый вариант заливается в грубую сетку.

Раскладка сравнивает реальные силуэты, а не прямоугольники вокруг них: так телефон
не ложится на наушники, если их рамки пересекаются только пустыми углами.
Запуск: python tools/build-masks.py  →  dist/masks.mjs
"""
import base64
import json
import re
from pathlib import Path
from xml.etree import ElementTree as ET

from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
CELL = 12  # единиц документа L на клетку сетки
SVG = '{http://www.w3.org/2000/svg}'


class FlattenPen(BasePen):
    """Превращает кривые в ломаные и собирает замкнутые контуры."""

    def __init__(self):
        super().__init__(None)
        self.polygons, self.current = [], []

    def _moveTo(self, pt):
        self._flush()
        self.current = [pt]

    def _lineTo(self, pt):
        self.current.append(pt)

    def _curveToOne(self, p1, p2, p3):
        p0 = self.current[-1]
        for i in range(1, 9):
            t = i / 8
            u = 1 - t
            self.current.append((
                u ** 3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t ** 3 * p3[0],
                u ** 3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t ** 3 * p3[1],
            ))

    def _qCurveToOne(self, p1, p2):
        p0 = self.current[-1]
        for i in range(1, 7):
            t = i / 6
            u = 1 - t
            self.current.append((u * u * p0[0] + 2 * u * t * p1[0] + t * t * p2[0],
                                 u * u * p0[1] + 2 * u * t * p1[1] + t * t * p2[1]))

    def _closePath(self):
        self._flush()

    def _endPath(self):
        self._flush()

    def _flush(self):
        if len(self.current) > 2:
            self.polygons.append(self.current)
        self.current = []


def polygons(body):
    root = ET.fromstring(f'<svg xmlns="http://www.w3.org/2000/svg">{body}</svg>')
    pen = FlattenPen()
    for node in root.iter():
        tag = node.tag.removeprefix(SVG)
        if tag == 'path' and node.get('fill') != 'none' or tag == 'path' and node.get('stroke'):
            parse_path(re.sub(r'@@\d@@', '', node.get('d', '')), pen)
            pen._flush()
        elif tag == 'rect':
            x, y = float(node.get('x', 0)), float(node.get('y', 0))
            if transform := node.get('transform'):
                dx, dy = (float(n) for n in re.findall(r'-?[.\d]+', transform)[:2])
                x, y = x + dx, y + dy
            w, h = float(node.get('width')), float(node.get('height'))
            pen.polygons.append([(x, y), (x + w, y), (x + w, y + h), (x, y + h)])
    return pen.polygons


def mask(fragment):
    x0, y0, w, h = fragment['box']
    cols, rows = -(-w // CELL), -(-h // CELL)
    # Рисуем в 4 раза мельче клетки и сжимаем: клетка считается занятой, если закрашена заметно.
    image = Image.new('L', (cols * 4, rows * 4), 0)
    draw = ImageDraw.Draw(image)
    for poly in polygons(fragment['body']):
        draw.polygon([((px - x0) / CELL * 4, (py - y0) / CELL * 4) for px, py in poly], fill=255)
    small = image.resize((cols, rows), Image.BOX)
    bits = bytearray((cols * rows + 7) // 8)
    filled = 0
    for index, value in enumerate(small.get_flattened_data()):
        if value > 70:
            bits[index // 8] |= 1 << (index % 8)
            filled += 1
    return {'cols': cols, 'rows': rows, 'filled': filled, 'bits': base64.b64encode(bytes(bits)).decode()}


def main():
    source = (ROOT / 'dist' / 'assets.mjs').read_text(encoding='utf-8')
    catalog = json.loads(re.search(r'export const CATALOG = (\[.*?\]);\n', source, re.S).group(1))
    masks = {}
    for asset in catalog:
        masks[asset['id']] = {role: mask(asset['variants']['L'][role]) for role in ('main', 'background')}
        print(asset['id'], {role: f"{m['cols']}x{m['rows']} {m['filled']}" for role, m in masks[asset['id']].items()})
    body = ('// Generated by tools/build-masks.py: silhouettes of L variants, one bit per '
            f'{CELL}×{CELL} document units.\n'
            f'export const MASK_CELL = {CELL};\n'
            'export const MASKS = ' + json.dumps(masks, separators=(',', ':')) + ';\n')
    (ROOT / 'dist' / 'masks.mjs').write_bytes(body.encode('utf-8'))


if __name__ == '__main__':
    main()
